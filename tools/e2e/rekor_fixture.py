"""Select a real Rekor backend without changing required signing or verification."""
import json
import os
from pathlib import Path
import re
from urllib.parse import urlsplit


def rekor_url(value=None):
    value = value if value is not None else os.environ.get("E2E_REKOR_URL", "https://rekor.sigstore.dev")
    parsed = urlsplit(value)
    if (parsed.scheme not in {"http", "https"} or not parsed.hostname
            or parsed.username or parsed.password or parsed.query or parsed.fragment
            or any(character.isspace() for character in value)):
        raise ValueError("E2E_REKOR_URL must be an HTTP(S) service URL without credentials or query parameters")
    return value.rstrip("/")


def configure_spec(path):
    """Update a generated fixture only when an alternate backend was requested."""
    if not os.environ.get("E2E_REKOR_URL"):
        return
    path = Path(path)
    contents = path.read_text()
    url = rekor_url()
    target = "/etc/systemd/system/confidential-agentd.service.d/30-e2e-rekor.conf"
    source = path.parent / ".e2e-rekor-trust.conf"

    def write_guest_allowlist():
        # Peers still enforce an explicit allowlist. The isolated test service
        # is trusted by name, alongside the default public transparency log.
        value = "CA_TRUSTED_REKOR_URLS=https://rekor.sigstore.dev," + url
        source.write_text("[Service]\nEnvironment=" + json.dumps(value) + "\n")

    if contents.lstrip().startswith("{"):
        spec = json.loads(contents)
        attestation = spec.get("attestation", {})
        if attestation.get("reference_values") != "rekor":
            return
        attestation.setdefault("rekor", {})["rekor_url"] = url
        if spec.get("build") is not None:
            write_guest_allowlist()
            files = spec["build"].setdefault("files", [])
            if not any(file.get("target") == target for file in files):
                files.append({"source": str(source.resolve()), "target": target})
        path.write_text(json.dumps(spec, indent=2) + "\n")
        return
    # Native YAML fixtures have one top-level attestation.rekor mapping. Keep
    # every other setting and private path exactly as generated by init.
    blocks = list(re.finditer(r"(?m)^  rekor: *$", contents))
    if not blocks:
        return
    if len(blocks) != 1:
        raise ValueError("ambiguous Rekor mappings in generated fixture")
    encoded = json.dumps(url)
    if re.search(r"(?m)^    rekor_url:", contents):
        contents = re.sub(r"(?m)^    rekor_url:.*$", "    rekor_url: " + encoded, contents)
    else:
        contents = contents[:blocks[0].end()] + "\n    rekor_url: " + encoded + contents[blocks[0].end():]
    if re.search(r"(?m)^build: *$", contents):
        write_guest_allowlist()
        if target not in contents:
            entry = "\n    - source: " + json.dumps(str(source.resolve())) + "\n      target: " + target
            if re.search(r"(?m)^  files: *$", contents):
                contents = re.sub(r"(?m)^  files: *$", "  files:" + entry, contents, count=1)
            else:
                if re.search(r"(?m)^  files:", contents):
                    raise ValueError("alternate Rekor fixture requires a block-style build.files list")
                contents = re.sub(r"(?m)^build: *$", "build:\n  files:" + entry, contents, count=1)
    path.write_text(contents)
